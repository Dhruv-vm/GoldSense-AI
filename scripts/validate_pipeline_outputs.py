from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
import pandas as pd


def validate_pipeline_outputs(root_dir: Path | None = None) -> tuple[bool, list[str]]:
    """
    Validates the outputs generated by update_pipeline.py:
      1. kjpl_events.csv
      2. market_features.csv
      3. analyzed_news.csv
      4. gold_training_dataset.csv
      5. evaluation_report.json

    Returns (is_valid, error_messages).
    """
    errors: list[str] = []
    root = root_dir or Path(__file__).resolve().parent.parent
    data_dir = root / "backend/ml/data/processed"

    if not data_dir.exists():
        return False, [f"Processed data directory not found: {data_dir}"]

    # 1. Validate kjpl_events.csv
    kjpl_path = data_dir / "kjpl_events.csv"
    if not kjpl_path.exists():
        errors.append(f"Missing file: {kjpl_path}")
        df_kjpl = None
    else:
        try:
            df_kjpl = pd.read_csv(kjpl_path)
            if len(df_kjpl) < 10:
                errors.append(f"kjpl_events.csv has only {len(df_kjpl)} rows (expected >= 10)")
            required_kjpl_cols = [
                "event_id", "event_time", "gold_mjdta", "silver_mjdta",
                "next_event_gold", "target_change", "target_direction"
            ]
            for col in required_kjpl_cols:
                if col not in df_kjpl.columns:
                    errors.append(f"kjpl_events.csv missing column: {col}")

            # Verify chronological order
            times = pd.to_datetime(df_kjpl["event_time"], utc=True)
            if not times.is_monotonic_increasing:
                errors.append("kjpl_events.csv event_time is not strictly monotonic increasing")

            # Verify zero-lookahead: last row must not have future target
            if not pd.isna(df_kjpl.iloc[-1]["next_event_gold"]):
                errors.append("kjpl_events.csv last row unexpectedly has a next_event_gold target")
        except Exception as e:
            errors.append(f"Failed to parse kjpl_events.csv: {e}")
            df_kjpl = None

    # 2. Validate market_features.csv
    mkt_path = data_dir / "market_features.csv"
    if not mkt_path.exists():
        errors.append(f"Missing file: {mkt_path}")
    else:
        try:
            df_mkt = pd.read_csv(mkt_path)
            if len(df_mkt) < 50:
                errors.append(f"market_features.csv has only {len(df_mkt)} rows (expected >= 50)")
            required_mkt_cols = ["observed_at", "usdinr", "xauusd", "xagusd", "market_stale"]
            for col in required_mkt_cols:
                if col not in df_mkt.columns:
                    errors.append(f"market_features.csv missing column: {col}")
        except Exception as e:
            errors.append(f"Failed to parse market_features.csv: {e}")

    # 3. Validate analyzed_news.csv
    news_path = data_dir / "analyzed_news.csv"
    if not news_path.exists():
        errors.append(f"Missing file: {news_path}")
    else:
        try:
            df_news = pd.read_csv(news_path)
            if len(df_news) < 100:
                errors.append(f"analyzed_news.csv has only {len(df_news)} rows (expected >= 100)")
            required_news_cols = [
                "published_at", "title", "url", "source",
                "sentiment_score", "sentiment_label", "is_gold_relevant", "primary_category"
            ]
            for col in required_news_cols:
                if col not in df_news.columns:
                    errors.append(f"analyzed_news.csv missing column: {col}")

            # Check bounds on sentiment_score
            scores = df_news["sentiment_score"].dropna()
            if (scores < -1.0).any() or (scores > 1.0).any():
                errors.append("analyzed_news.csv contains sentiment_scores outside [-1.0, 1.0]")
        except Exception as e:
            errors.append(f"Failed to parse analyzed_news.csv: {e}")

    # 4. Validate gold_training_dataset.csv
    train_path = data_dir / "gold_training_dataset.csv"
    if not train_path.exists():
        errors.append(f"Missing file: {train_path}")
    else:
        try:
            df_train = pd.read_csv(train_path)
            if df_kjpl is not None:
                expected_rows = len(df_kjpl) - 1
                if len(df_train) != expected_rows:
                    errors.append(
                        f"gold_training_dataset.csv has {len(df_train)} rows; expected len(kjpl_events)-1 = {expected_rows}"
                    )

            required_train_cols = [
                "event_id", "event_time", "gold_mjdta", "target_change", "target_direction",
                "usdinr", "xauusd", "sentiment_mean_1d", "gold_sentiment_mean_1d"
            ]
            for col in required_train_cols:
                if col not in df_train.columns:
                    errors.append(f"gold_training_dataset.csv missing column: {col}")

            # Verify no future leakage: market_observed_at <= event_time
            if "market_observed_at" in df_train.columns:
                mkt_times = pd.to_datetime(df_train["market_observed_at"].dropna(), utc=True)
                ev_times = pd.to_datetime(df_train.loc[df_train["market_observed_at"].notna(), "event_time"], utc=True)
                if not (mkt_times <= ev_times).all():
                    errors.append("gold_training_dataset.csv contains market_observed_at > event_time (lookahead leakage)")
        except Exception as e:
            errors.append(f"Failed to parse gold_training_dataset.csv: {e}")

    # 5. Validate evaluation_report.json
    rep_path = data_dir / "evaluation_report.json"
    if not rep_path.exists():
        errors.append(f"Missing file: {rep_path}")
    else:
        try:
            with rep_path.open("r", encoding="utf-8") as f:
                report = json.load(f)
            if report.get("status") not in ("INSUFFICIENT_DATA_FOR_SUPERVISED_TRAINING", "READY_FOR_TRAINING"):
                errors.append(f"evaluation_report.json has unexpected status: {report.get('status')}")
            if "baseline_benchmarks" not in report:
                errors.append("evaluation_report.json missing 'baseline_benchmarks'")
            if "dataset_metadata" not in report:
                errors.append("evaluation_report.json missing 'dataset_metadata'")
            else:
                meta = report["dataset_metadata"]
                if meta.get("min_required_threshold") != 50:
                    errors.append(f"evaluation_report.json threshold is {meta.get('min_required_threshold')} (expected 50)")
        except Exception as e:
            errors.append(f"Failed to parse evaluation_report.json: {e}")

    is_valid = len(errors) == 0
    return is_valid, errors


def main() -> int:
    parser = argparse.ArgumentParser(description="Validate GoldSense AI pipeline outputs.")
    parser.add_argument("--root-dir", type=Path, default=None, help="Root directory of repository")
    args = parser.parse_args()

    print("[PIPELINE VALIDATION] Validating processed dataset and evaluation outputs...")
    is_valid, errors = validate_pipeline_outputs(args.root_dir)

    if not is_valid:
        print("[PIPELINE VALIDATION] FAILURES DETECTED:")
        for err in errors:
            print(f"  - {err}")
        return 1

    print("[PIPELINE VALIDATION] SUCCESS: All 5 pipeline output artifacts verified.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
